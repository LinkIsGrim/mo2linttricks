def make_instance(root: Path) -> snapshot.InstanceInfo:
    mods, profiles, downloads = root / "mods", root / "profiles", root / "downloads"
    for d in (mods / "Cyber Engine Tweaks", mods / "My URL Mod", mods / "Frameworks_separator", mods / "RED4ext", profiles / "Default", downloads):
        d.mkdir(parents=True)
    (mods / "Cyber Engine Tweaks" / "meta.ini").write_text(META_CET)
    (mods / "My URL Mod" / "meta.ini").write_text(META_URL)
    (mods / "RED4ext" / "meta.ini").write_text("[General]\ninstallationFile=RED4ext-1.27.zip\nversion=1.27\n")
    (downloads / "RED4ext-1.27.zip.meta").write_text(DL_META)
    (downloads / "RED4ext-1.27.zip").write_bytes(b"zip")
    (profiles / "Default" / "modlist.txt").write_text(MODLIST)
    (profiles / "Default" / "settings.ini").write_text("[General]\nLocalSaves=false\n")
    (profiles / "Default" / "saves").mkdir()
    return snapshot.InstanceInfo(mods, profiles, downloads, "cyberpunk2077", "Cyberpunk 2077", "cyberpunk2077", "2.5.2")


class FakeGitHub:
    """Just enough of the GitHub REST + Git Data API for push_snapshot."""

    def __init__(self):
        self.blobs: dict[str, bytes] = {}
        self.trees: dict[str, dict[str, str]] = {}
        self.commits: dict[str, dict] = {}
        self.repos: dict[str, str] = {}  # full_name -> head
        self.calls = []

    def _tree(self, files):
        sha = hashlib.sha1(json.dumps(sorted(files.items())).encode()).hexdigest()
        self.trees[sha] = dict(files)
        return sha

    def _commit(self, tree, parents):
        sha = hashlib.sha1(f"{tree}{parents}{len(self.commits)}".encode()).hexdigest()
        self.commits[sha] = {"tree": tree, "parents": parents}
        return sha

    def __call__(self, method, url, headers=None, body=None):
        self.calls.append((method, url))
        path = url.replace(github.API, "")
        data = json.loads(body) if body else None
        ok = lambda d, s=200: Response(s, json.dumps(d).encode(), {})  # noqa: E731
        if path == "/user":
            return ok({"login": "tester"})
        if method == "GET" and path.startswith("/repos/tester/") and path.count("/") == 3:
            name = "tester/" + path.split("/")[3]
            return ok({"full_name": name}) if name in self.repos else Response(404, b'{"message":"Not Found"}', {})
        if method == "POST" and path == "/user/repos":
            full = "tester/" + data["name"]
            readme = b"# init\n"
            self.blobs[github.blob_sha(readme)] = readme
            self.repos[full] = self._commit(self._tree({"README.md": github.blob_sha(readme)}), [])
            return ok({"full_name": full}, 201)
        repo = "/".join(path.split("/")[2:4])
        rest = "/" + "/".join(path.split("/")[4:])
        if rest == "/git/ref/heads/main":
            return ok({"object": {"sha": self.repos[repo]}})
        if rest.startswith("/git/commits/") and method == "GET":
            c = self.commits[rest.split("/")[-1]]
            return ok({"tree": {"sha": c["tree"]}})
        if rest.startswith("/git/trees/") and method == "GET":
            t = self.trees[rest.split("/")[-1].split("?")[0]]
            return ok({"truncated": False, "tree": [{"path": p, "sha": s, "type": "blob"} for p, s in t.items()]})
        if rest == "/git/blobs" and method == "POST":
            raw = base64.b64decode(data["content"])
            self.blobs[github.blob_sha(raw)] = raw
            return ok({"sha": github.blob_sha(raw)}, 201)
        if rest == "/git/trees" and method == "POST":
            files = dict(self.trees[data["base_tree"]])
            for e in data["tree"]:
                if "content" in e:
                    raw = e["content"].encode()
                    self.blobs[github.blob_sha(raw)] = raw
                    files[e["path"]] = github.blob_sha(raw)
                elif e.get("sha") is None:
                    files.pop(e["path"], None)
                else:
                    files[e["path"]] = e["sha"]
            return ok({"sha": self._tree(files)}, 201)
        if rest == "/git/commits" and method == "POST":
            return ok({"sha": self._commit(data["tree"], data["parents"])}, 201)
        if rest == "/git/refs/heads/main" and method == "PATCH":
            self.repos[repo] = data["sha"]
            return ok({})
        raise AssertionError(f"unhandled {method} {url}")

    def files(self, repo):
        t = self.trees[self.commits[self.repos[repo]]["tree"]]
        return {p: self.blobs[s] for p, s in t.items()}


class SnapshotTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.info = make_instance(Path(self.tmp.name))

    def tearDown(self):
        self.tmp.cleanup()

    def test_modlist_order_and_kinds(self):
        entries = snapshot.parse_modlist(MODLIST)
        self.assertEqual([e["name"] for e in entries], ["DLC: Phantom Liberty", "RED4ext", "Frameworks_separator", "My URL Mod", "Cyber Engine Tweaks"])
        self.assertEqual([e["kind"] for e in entries], ["foreign", "mod", "separator", "mod", "mod"])
        self.assertEqual([e["enabled"] for e in entries], [True, True, True, False, True])

    def test_snapshot_sources(self):
        snap = snapshot.build(self.info)
        mods = json.loads(snap.files["mods.json"])
        self.assertEqual(mods["Cyber Engine Tweaks"]["source"], "nexus")
        self.assertEqual(mods["Cyber Engine Tweaks"]["fileids"], [91234])
        self.assertEqual(mods["My URL Mod"]["source"], "url")
        self.assertEqual(mods["My URL Mod"]["url"], "https://example.com/mymod")
        self.assertEqual(mods["RED4ext"]["source"], "nexus")  # ids come from downloads/*.meta
        self.assertEqual((mods["RED4ext"]["modid"], mods["RED4ext"]["fileids"]), (4198, [55555]))
        self.assertEqual(mods["Frameworks_separator"]["source"], "separator")
        self.assertNotIn(b"nexusDescription", snap.files["mods/Cyber Engine Tweaks/meta.ini"])
        self.assertIn("profiles/Default/settings.ini", snap.files)
        self.assertIn("downloads/RED4ext-1.27.zip.meta", snap.files)
        self.assertFalse(any("saves" in p for p in snap.files))

    def test_snapshot_is_deterministic(self):
        self.assertEqual(snapshot.build(self.info).files, snapshot.build(self.info).files)


class PushTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.info = make_instance(Path(self.tmp.name))
        self.fake = FakeGitHub()
        self.gh = github.GitHub("tok", self.fake)

    def tearDown(self):
        self.tmp.cleanup()

    def test_create_push_noop_update_delete(self):
        repo, created = self.gh.ensure_repo("mo2-mods-cyberpunk2077", "x")
        self.assertTrue(created)
        snap = snapshot.build(self.info)
        self.assertIsNotNone(self.gh.push_snapshot(repo, snap, "first"))
        remote = self.fake.files(repo)
        self.assertIn("README.md", remote)  # unmanaged files are kept
        for p, data in snap.files.items():
            self.assertEqual(remote[p], data)

        self.assertIsNone(self.gh.push_snapshot(repo, snapshot.build(self.info), "noop"))

        # remove a mod -> its meta.ini disappears from the repo
        import shutil
        shutil.rmtree(self.info.mods_dir / "My URL Mod")
        snap2 = snapshot.build(self.info)
        self.assertIsNotNone(self.gh.push_snapshot(repo, snap2, "remove"))
        self.assertNotIn("mods/My URL Mod/meta.ini", self.fake.files(repo))
        self.assertIn("README.md", self.fake.files(repo))
        msg = github.describe_changes(snap.files, snap2.files)
        self.assertIn("removed My URL Mod", msg)

    def test_ensure_repo_existing(self):
        self.gh.ensure_repo("r", "x")
        _, created = self.gh.ensure_repo("r", "x")
        self.assertFalse(created)


class DeviceFlowTests(unittest.TestCase):
    def test_pending_slowdown_then_token(self):
        answers = iter([{"error": "authorization_pending"}, {"error": "slow_down", "interval": 10}, {"access_token": "gho_x"}])
        slept = []

        def t(method, url, headers=None, body=None):
            return Response(200, json.dumps(next(answers)).encode(), {})

        code = github.DeviceCode("dc", "ABCD-1234", "https://github.com/login/device", 5, 900)
        self.assertEqual(github.poll_device_flow("cid", code, t, sleep=slept.append), "gho_x")
        self.assertEqual(slept, [5, 5, 10])

    def test_denied(self):
        t = lambda *a, **k: Response(200, b'{"error":"access_denied","error_description":"denied"}', {})  # noqa: E731
        code = github.DeviceCode("dc", "X", "u", 1, 900)
        with self.assertRaises(github.GitHubError):
            github.poll_device_flow("cid", code, t, sleep=lambda s: None)


class RestorePlanTests(unittest.TestCase):
    def test_plan_actions(self):
        with tempfile.TemporaryDirectory() as d:
            info = make_instance(Path(d))
            snap = snapshot.build(info)
            rows = restore.plan(snap.files["profiles/Default/modlist.json"], snap.files["mods.json"], {"Cyber Engine Tweaks"}, info.downloads_dir)
            actions = {r.name: r.action for r in rows}
            self.assertEqual(actions["Cyber Engine Tweaks"], restore.INSTALLED)
            self.assertEqual(actions["RED4ext"], restore.INSTALL_ARCHIVE)
            self.assertEqual(actions["My URL Mod"], restore.DOWNLOAD_URL)
            self.assertEqual(actions["Frameworks_separator"], restore.CREATE_SEPARATOR)
            self.assertEqual(actions["DLC: Phantom Liberty"], restore.GAME)
            rows = restore.plan(snap.files["profiles/Default/modlist.json"], snap.files["mods.json"], set(), Path(d) / "nope")
            cet = next(r for r in rows if r.name == "Cyber Engine Tweaks")
            self.assertEqual(cet.action, restore.DOWNLOAD_NEXUS)
            self.assertEqual(cet.nexus_ids, (107, 91234))
            self.assertIn("mods/107?tab=files&file_id=91234", cet.nexus_page("cyberpunk2077"))

    def test_parse_plugins(self):
        self.assertEqual(
            restore.parse_plugins(b"*A.esp\nB.esp\n", b"# x\nSkyrim.esm\nA.esp\nB.esp\n"),
            [("Skyrim.esm", False), ("A.esp", True), ("B.esp", False)],
        )


